/// Mirror of `RunFrame::write_slot_with_taint` at
/// `crates/vb_core/src/frame/parts/impl_003_slots_taints.rs:25-37`.
///
/// Production contract:
///   - Err(CoreError::SlotOutOfBounds { slot }) when
///     slot.as_usize() >= self.cells.len(). The mirror retains its
///     documented InvalidCompiledWorkflow error-token projection.
///   - Ok(()) and `self.cells[i] = SlotCell::Value { value, taint }`
///     otherwise.
#[verifier::external]
pub fn run_frame_write_slot_with_taint(
    frame: &mut RunFrame,
    slot: SlotIdx,
    value: SlotValue,
    taint: Taint,
) -> CoreResult<()> {
    let index = slot.as_usize();
    let cell = frame.cells.get_mut(index).ok_or(CoreError::SlotOutOfBounds { slot }).map_err(
        |error|
            match error {
                CoreError::SlotOutOfBounds { .. } => CoreError::InvalidCompiledWorkflow {
                    reason: "slot_index_out_of_bounds",
                },
                other => other,
            },
    )?;
    *cell = SlotCell::Value { value, taint };
    Ok(())
}

