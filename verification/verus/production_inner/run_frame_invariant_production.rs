/// Mirror of `RunFrame::new` at
/// `crates/vb_core/src/frame/parts/impl_001_construct.rs:35-55`.
///
/// Production contract:
///   - Err(CoreError::InvalidCompiledWorkflow { reason: "step_count_zero" })
///     when states_len == 0.
///   - Err(CoreError::InvalidProgramCounter { step: first_step })
///     when first_step.as_usize() >= states_len.
///   - Err(CoreError::AllocationFailed) after valid dimensions if reservation
///     fails or a nonzero-sized array has a different capacity.
///   - Ok(Self { run_id, pc: first_step, executed: 0, step_count,
///       slot_count, max_parallel_in_flight: u16::MAX,
///       parallel_in_flight: 0, states: Pending repeated states_len times,
///       cells: Empty repeated slot_count times })
///     otherwise.
#[verifier::external]
pub fn run_frame_new(
    run_id: RunId,
    first_step: StepIdx,
    step_count: u16,
    slot_count: u16,
) -> CoreResult<RunFrame> {
    let states_len = usize::from(step_count);
    if states_len == 0 {
        return Err(CoreError::InvalidCompiledWorkflow { reason: "step_count_zero" });
    }
    if first_step.as_usize() >= states_len {
        return Err(CoreError::InvalidProgramCounter { step: first_step });
    }
    let slots_len = usize::from(slot_count);
    type FrameArrays = (Box<[StepState]>, Box<[SlotCell]>);
    fn try_frame_array<T>(len: usize, make: impl FnMut() -> T) -> CoreResult<Box<[T]>> {
        let mut values = Vec::new();
        values.try_reserve_exact(len).map_err(|_error| CoreError::AllocationFailed)?;
        if core::mem::size_of::<T>() != 0 && values.capacity() != len {
            return Err(CoreError::AllocationFailed);
        }
        values.resize_with(len, make);
        Ok(values.into_boxed_slice())
    }
    fn frame_arrays(states_len: usize, slots_len: usize) -> CoreResult<FrameArrays> {
        let states = try_frame_array(states_len, || StepState::Pending)?;
        let cells = try_frame_array(slots_len, || SlotCell::Empty)?;
        Ok((states, cells))
    }
    let (states, cells) = frame_arrays(states_len, slots_len)?;
    Ok(
        RunFrame {
            run_id,
            pc: first_step,
            executed: 0,
            step_count,
            slot_count,
            max_parallel_in_flight: u16::MAX,
            parallel_in_flight: 0,
            states,
            cells,
        },
    )
}

/// Mirror of `RunFrame::reinitialize` at
/// `crates/vb_core/src/frame/parts/impl_001_construct.rs:60-94`.
///
/// Production contract:
///   - Err(CoreError::InvalidCompiledWorkflow { reason: "step_count_zero" })
///     when states_len == 0.
///   - Err(CoreError::InvalidProgramCounter { step: first_step })
///     when first_step.as_usize() >= states_len.
///   - Err(CoreError::InvalidCompiledWorkflow { reason: "frame_dimension_mismatch" })
///     when self.step_count != step_count || self.slot_count != slot_count.
///   - Ok(()) after resetting run_id, pc, executed, max_parallel_in_flight,
///     parallel_in_flight, all states to Pending and all cells to Empty.
#[verifier::external]
pub fn run_frame_reinitialize(
    frame: &mut RunFrame,
    run_id: RunId,
    first_step: StepIdx,
    step_count: u16,
    slot_count: u16,
) -> CoreResult<()> {
    let states_len = usize::from(step_count);
    if states_len == 0 {
        return Err(CoreError::InvalidCompiledWorkflow { reason: "step_count_zero" });
    }
    if first_step.as_usize() >= states_len {
        return Err(CoreError::InvalidProgramCounter { step: first_step });
    }
    if frame.step_count != step_count || frame.slot_count != slot_count {
        return Err(CoreError::InvalidCompiledWorkflow { reason: "frame_dimension_mismatch" });
    }
    frame.run_id = run_id;
    frame.pc = first_step;
    frame.executed = 0;
    frame.max_parallel_in_flight = u16::MAX;
    frame.parallel_in_flight = 0;
    for state in frame.states.iter_mut() {
        *state = StepState::Pending;
    }
    for cell in frame.cells.iter_mut() {
        *cell = SlotCell::Empty;
    }
    Ok(())
}

