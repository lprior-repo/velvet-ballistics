/// Shrinkable bounds for Collect string fields (variable, source).
#[derive(Debug, Clone, kani::Arbitrary)]
pub struct BoundedString {
    pub value: [u8; 64],
    pub len: usize,
}

impl BoundedString {
    pub fn as_str(&self) -> &str {
        std::str::from_utf8(&self.value[..self.len]).unwrap_or("")
    }
}

/// kani::Arbitrary for StepPrimitive::Collect with bounded fields.
/// Bounds: variable 0..64 chars, source 0..64 chars,
///         pages 0..100, items 0..1000, body 0..8 steps.
impl kani::Arbitrary for StepPrimitive::Collect {
    fn any() -> Self {
        let variable = kani::any::<BoundedString>();
        let source = kani::any::<BoundedString>();
        let pages = kani::any::<Option<u32>>();
        let items = kani::any::<Option<u32>>();
        let body_len = usize::from(kani::any::<u8>() % 9); // 0..8
        let body: Vec<StepAst> = (0..body_len)
            .map(|_| {
                let id = kani::any::<BoundedString>();
                StepAst {
                    id: id.as_str().to_string(),
                    name: None,
                    condition: None,
                    primitive: StepPrimitive::Finish {
                        result: vb_yaml::ast::ScalarValue::Integer(0),
                    },
                    with: None,
                    retry: None,
                    on_error: None,
                    then: None,
                }
            })
            .collect();

        StepPrimitive::Collect {
            variable: variable.as_str().to_string(),
            source: source.as_str().to_string(),
            pages: pages.map(|p| p % 101),        // 0..100
            items: items.map(|i| i % 1001),       // 0..1000
            body,
        }
    }
}

// ─────────────────────────────────────────────────────────────────
// Test 1: Different pages produce different digests (POST-FIX)
//
// PRE-FIX (bug): digest_a == digest_b because only "collect" name is hashed.
// POST-FIX (fix): digest_a != digest_b because pages field contributes to digest.
// ─────────────────────────────────────────────────────────────────

#[kani::proof]
#[kani::unwind(6)]
fn kani_collect_different_pages_different_digest() {
    // Two Collect primitives identical except pages differs.
    let base = StepPrimitive::Collect {
        variable: "x".to_string(),
        source: "items".to_string(),
        pages: Some(10),
        items: Some(50),
        body: vec![],
    };

    let mut different_pages = base.clone();
    if let StepPrimitive::Collect { pages: ref mut p, .. } = different_pages {
        *p = Some(999);
    }

    // Hash both using the actual digest_step_primitive
    let mut hasher_a = blake3::Hasher::new();
    let mut hasher_b = blake3::Hasher::new();

    digest_step_primitive(&mut hasher_a, &base);
    digest_step_primitive(&mut hasher_b, &different_pages);

    let digest_a = hasher_a.finalize();
    let digest_b = hasher_b.finalize();

    // POST-FIX: different pages MUST produce different digests
    kani::cover!(digest_a != digest_b, "different pages -> different digest (POST-FIX)");
    // PRE-FIX (bug): kani::cover!(digest_a == digest_b) would PASS, proving the bug
}

