// ─────────────────────────────────────────────────────────────────
// kani::Arbitrary for StepPrimitive::Aggregate with bounded fields.
// Bounds: variable 0..64 chars, input 0..64 chars,
//         initial 0..64 chars, body 0..8 steps.
// ─────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, kani::Arbitrary)]
pub struct BoundedString {
    pub value: [u8; 64],
    pub len: usize,
}

impl BoundedString {
    pub fn as_str(&self) -> &str {
        std::str::from_utf8(&self.value[..self.len]).unwrap_or("")
    }
}

impl kani::Arbitrary for StepPrimitive::Aggregate {
    fn any() -> Self {
        let variable = kani::any::<BoundedString>();
        let input = kani::any::<BoundedString>();
        let initial = kani::any::<BoundedString>();
        let body_len = usize::from(kani::any::<u8>() % 9); // 0..8
        let body: Vec<StepAst> = (0..body_len)
            .map(|_| {
                let id = kani::any::<BoundedString>();
                StepAst {
                    id: id.as_str().to_string(),
                    name: None,
                    condition: None,
                    primitive: StepPrimitive::Finish {
                        result: vb_yaml::ast::ScalarValue::Integer(0),
                    },
                    with: None,
                    retry: None,
                    on_error: None,
                    then: None,
                }
            })
            .collect();

        StepPrimitive::Aggregate {
            variable: variable.as_str().to_string(),
            input: input.as_str().to_string(),
            initial: initial.as_str().to_string(),
            body,
        }
    }
}

