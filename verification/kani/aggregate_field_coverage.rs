// ─────────────────────────────────────────────────────────────────
// Internal digest_primitive (mirrors actual implementation for testing)
// ─────────────────────────────────────────────────────────────────

fn digest_primitive(hasher: &mut blake3::Hasher, primitive: &StepPrimitive) {
    match primitive {
        StepPrimitive::Set { output, value } => {
            hasher.update(b"set");
            hasher.update(output.as_bytes());
            hasher.update(value.as_bytes());
        }
        StepPrimitive::Finish { result } => {
            hasher.update(b"finish");
            match result {
                vb_yaml::ast::ScalarValue::String(v) => hasher.update(v.as_bytes()),
                vb_yaml::ast::ScalarValue::Integer(v) => hasher.update(&v.to_le_bytes()),
                _ => hasher.update(b"unsupported"),
            };
        }
        other => {
            let name = canonical_primitive_name(other);
            hasher.update(name.as_bytes());
        }
    }
}

fn canonical_primitive_name(primitive: &StepPrimitive) -> &'static str {
    match primitive {
        StepPrimitive::Set { .. } => "set",
        StepPrimitive::Save { .. } => "save",
        StepPrimitive::Do { .. } => "do",
        StepPrimitive::Choose { .. } => "choose",
        StepPrimitive::ForEach { .. } => "for_each",
        StepPrimitive::Together { .. } => "parallel",
        StepPrimitive::Collect { .. } => "collect",
        StepPrimitive::Aggregate { .. } => "aggregate",
        StepPrimitive::Repeat { .. } => "repeat",
        StepPrimitive::Wait { .. } => "wait",
        StepPrimitive::Ask { .. } => "ask",
        StepPrimitive::Finish { .. } => "finish",
        _ => "unknown",
    }
}
