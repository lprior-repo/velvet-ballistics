fn require(condition: bool, message: &str) -> TestResult {
    if condition {
        Ok(())
    } else {
        Err(message.into())
    }
}

fn check_wire<T: Serialize + DeserializeOwned + PartialEq + Debug>(
    bytes: &[u8],
    expected: &T,
) -> TestResult {
    let (decoded, remainder) = postcard::take_from_bytes::<T>(bytes)?;
    require(remainder.is_empty(), "unconsumed golden bytes")?;
    if &decoded != expected {
        return Err(format!("decoded {decoded:?}, expected {expected:?}").into());
    }
    require(
        postcard::to_allocvec(expected)?.as_slice() == bytes,
        "encoding differs from historical source-derived literal",
    )?;
    let (_, truncated) = bytes.split_last().ok_or("empty golden fixture")?;
    require(
        postcard::take_from_bytes::<T>(truncated).is_err(),
        "truncated historical record was accepted",
    )
}

