#[test]
fn grant_digest_preserves_exact_fixed_bytes_without_a_length_prefix() -> TestResult {
    let expected = GrantDigest::from_bytes(DIGEST_BYTES);
    require(expected.as_bytes() == DIGEST_BYTES, "digest bytes changed")?;
    check_wire(&DIGEST_BYTES, &expected)
}

