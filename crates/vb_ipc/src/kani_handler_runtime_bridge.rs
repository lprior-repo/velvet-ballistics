/// handle_answer_ask returns RuntimeError for invalid postcard SlotValue
/// without calling Runtime::answer_pending_ask_slot (fail-closed).
#[kani::proof]
#[kani::unwind(6)]
fn kani_malformed_slot_value_rejected_before_mutation() {
    let mut runtime = make_runtime();
    let run = arbitrary_run_id();
    let ask_step = StepIdx::new(0);
    let resume_step = StepIdx::new(1);
    let answer_slot = arbitrary_slot();

    // Set up pending ask
    setup_pending_ask_shard(&mut runtime, run, ask_step, resume_step, answer_slot);

    // Record initial shard state (before calling handle_answer_ask)
    let shard_before = runtime.shards_mut().first().expect("1 shard").clone();

    // Create a malformed payload: invalid postcard bytes
    let malformed_answer = vec![0xff, 0xfe, 0xfd];

    let payload_bytes = encode_answer_ask_payload(run, answer_slot, &malformed_answer, None)
        .expect("AnswerAsk serialization should succeed");

    // Call the REAL handle_answer_ask function
    let response = handle_answer_ask(&payload_bytes, &mut runtime);

    // Verify: malformed SlotValue must be rejected
    // kani::cover! covered by verification
    // Must NOT be BadRequest (the payload itself is well-formed)
    kani::assert(
        !matches!(response, IpcResponse::BadRequest),
        "well-formed AnswerAsk must not produce BadRequest",
    );
    // Verify: shard state was NOT mutated (fail-closed guarantee)
    let shard_after = runtime.shards_mut().first().expect("1 shard").clone();
    kani::assert(
        shard_before.runtime_state_get(run) == shard_after.runtime_state_get(run),
        "shard state must not change on malformed SlotValue",
    );
}

