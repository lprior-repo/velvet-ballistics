/// Constructs a minimal Runtime with 1 shard.
/// This is sufficient for bridge-routing verification.
fn make_runtime() -> Runtime {
    let config = ShardConfig::default();
    Runtime::new(NonZeroUsize::MIN, config)
}

/// Constructs an arbitrary but bounded RunId.
fn arbitrary_run_id() -> RunId {
    let val: u64 = kani::any();
    kani::assume(val > 0);
    RunId::new(val)
}

/// Constructs an arbitrary but bounded SlotIdx.
fn arbitrary_slot() -> SlotIdx {
    let val: u16 = kani::any();
    SlotIdx::new(val)
}

/// Sets up a shard with a pending Ask timer and an Ask node + AskResume node.
/// Returns the setup payload: (ask_step, resume_step, answer_slot, run_id).
fn setup_pending_ask_shard(
    runtime: &mut Runtime,
    run: RunId,
    ask_step: StepIdx,
    resume_step: StepIdx,
    answer_slot: SlotIdx,
) {
    // Set the shard to Resumable state with a pending timer
    runtime
        .shards_mut()
        .first_mut()
        .expect("Runtime has 1 shard")
        .apply(run, RuntimeEvent::AwaitTimer);

    // Set pending timer to Ask kind
    let shard = runtime
        .shards_mut()
        .first_mut()
        .expect("Runtime has 1 shard");
    shard.set_pending_timer(
        run,
        PendingTimer {
            step: ask_step,
            kind: PendingTimerKind::Ask,
        },
    );

    // Set the workflow with Ask node at ask_step and AskResume at resume_step
    let workflow = vb_core::workflow::CompiledWorkflow::from_parts(
        "bridge-test"
            .try_into()
            .unwrap_or_else(|_| "bridge-test".try_into().unwrap()),
        vec![
            vb_core::workflow::CompiledNode {
                id: ask_step,
                output: None,
                next: Some(resume_step),
                on_error: None,
                error_slot: None,
                kind: CompiledNodeKind::Ask {},
            },
            vb_core::workflow::CompiledNode {
                id: resume_step,
                output: None,
                next: None,
                on_error: None,
                error_slot: None,
                kind: CompiledNodeKind::AskResume {
                    answer: answer_slot,
                },
            },
        ],
        vec![],
        None,
        None,
        vb_core::workflow::ShardConfig::default(),
    )
    .unwrap_or_else(|_| {
        // Fallback: create a minimal workflow that won't crash
        vb_core::workflow::CompiledWorkflow::from_parts(
            "bridge-test".try_into().unwrap(),
            vec![],
            vec![],
            None,
            None,
            vb_core::workflow::ShardConfig::default(),
        )
        .expect("fallback workflow must succeed")
    });

    // Set run state with the workflow
    shard.set_run_state(
        run,
        vb_runtime::shard::RunState {
            runtime_state: RuntimeState::Resumable,
            workflow,
            journal_seq: vb_core::ids::EventSeq::new(0),
        },
    );
}

/// Serializes an IpcPayload::AnswerAsk into bytes using postcard.
/// Returns None if serialization fails (should not fail for well-formed inputs).
fn encode_answer_ask_payload(
    run_id: RunId,
    answer_slot: SlotIdx,
    answer: &[u8],
    taint: Option<Taint>,
) -> Option<Vec<u8>> {
    let payload = IpcPayload::AnswerAsk {
        run_id,
        answer_slot,
        answer: answer.to_vec(),
        taint,
    };
    postcard::to_allocvec(&payload).ok()
}

/// Serializes a SlotValue into postcard bytes.
fn encode_slot_value(value: &SlotValue) -> Option<Vec<u8>> {
    postcard::to_allocvec(value).ok()
}

